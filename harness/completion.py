"""Code-based completion criteria for the flight booking harness.

Verifies task completion against the real state in the mock database rather than
trusting conversational claims generated by the LLM.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from data.flights import get_booking, get_flight_by_id


@dataclass
class CompletionResult:
    """Structured report verifying whether a task actually completed in state."""
    completed: bool
    reason: str
    evidence: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "completed": self.completed,
            "reason": self.reason,
            "evidence": self.evidence,
        }


def check_booking_completed(
    booking_id: Optional[str] = None,
    expected_flight_id: Optional[str] = None,
    expected_passenger: Optional[str] = None,
) -> CompletionResult:
    """Verify that a booking has genuinely been committed to the database and confirmed.

    Criteria:
    1. A valid booking_id must be provided.
    2. The booking must exist in the in-memory database.
    3. The booking status must strictly be 'CONFIRMED'.
    4. The associated flight must exist in the flight catalog.
    5. If expected flight or passenger are specified, they must match the record.
    """
    if not booking_id:
        return CompletionResult(
            completed=False,
            reason="No booking_id provided for completion verification.",
            evidence={"booking_id": booking_id},
        )

    booking = get_booking(booking_id)
    if not booking:
        return CompletionResult(
            completed=False,
            reason=f"Booking record '{booking_id}' does not exist in the database.",
            evidence={"booking_id": booking_id, "found": False},
        )

    if booking.get("status") != "CONFIRMED":
        return CompletionResult(
            completed=False,
            reason=f"Booking '{booking_id}' has status '{booking.get('status')}', expected 'CONFIRMED'.",
            evidence={"booking": booking},
        )

    flight = get_flight_by_id(booking["flight_id"])
    if not flight:
        return CompletionResult(
            completed=False,
            reason=f"Flight '{booking['flight_id']}' referenced by booking does not exist.",
            evidence={"booking": booking, "flight_id": booking["flight_id"]},
        )

    if expected_flight_id and booking["flight_id"].upper() != expected_flight_id.upper():
        return CompletionResult(
            completed=False,
            reason=f"Booking flight '{booking['flight_id']}' does not match expected flight '{expected_flight_id}'.",
            evidence={"actual_flight": booking["flight_id"], "expected_flight": expected_flight_id},
        )

    if expected_passenger and expected_passenger.strip().lower() not in booking["passenger_name"].lower():
        return CompletionResult(
            completed=False,
            reason=f"Passenger '{booking['passenger_name']}' does not match expected '{expected_passenger}'.",
            evidence={"actual_passenger": booking["passenger_name"], "expected_passenger": expected_passenger},
        )

    return CompletionResult(
        completed=True,
        reason="Booking exists, is confirmed in database, and matches expected criteria.",
        evidence={"booking": booking, "flight": flight},
    )


def check_cancellation_completed(
    booking_id: Optional[str] = None,
) -> CompletionResult:
    """Verify that a booking has genuinely been cancelled and updated in the database."""
    if not booking_id:
        return CompletionResult(
            completed=False,
            reason="No booking_id provided for cancellation verification.",
            evidence={"booking_id": booking_id},
        )

    booking = get_booking(booking_id)
    if not booking:
        return CompletionResult(
            completed=False,
            reason=f"Booking '{booking_id}' not found in database.",
            evidence={"booking_id": booking_id, "found": False},
        )

    if booking.get("status") != "CANCELLED":
        return CompletionResult(
            completed=False,
            reason=f"Booking '{booking_id}' status is '{booking.get('status')}', expected 'CANCELLED'.",
            evidence={"booking": booking},
        )

    return CompletionResult(
        completed=True,
        reason=f"Booking '{booking_id}' is verified as CANCELLED in database.",
        evidence={"booking": booking},
    )


def check_search_completed(
    search_results: Optional[List[Dict[str, Any]]] = None,
) -> CompletionResult:
    """Verify that a flight search completed and produced valid flight results."""
    if search_results is None:
        return CompletionResult(
            completed=False,
            reason="Search results were not provided.",
            evidence={"results": None},
        )

    return CompletionResult(
        completed=True,
        reason=f"Search completed successfully with {len(search_results)} item(s).",
        evidence={"count": len(search_results), "results": search_results},
    )
